CREATE TABLE IF NOT EXISTS ng_users (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(64) NOT NULL,
  pass_hash VARCHAR(255) NOT NULL,
  display_name VARCHAR(64) NOT NULL,
  color VARCHAR(16) NOT NULL DEFAULT '#3b82f6',
  emoji VARCHAR(16) NOT NULL DEFAULT '',
  is_admin TINYINT(1) NOT NULL DEFAULT 0,
  created_at INT UNSIGNED NOT NULL,
  UNIQUE KEY uq_username (username)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS ng_tokens (
  token_hash CHAR(64) NOT NULL PRIMARY KEY,
  user_id INT UNSIGNED NOT NULL,
  expires_at INT UNSIGNED NOT NULL,
  KEY k_user (user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS ng_presence (
  user_id INT UNSIGNED NOT NULL PRIMARY KEY,
  peer_id VARCHAR(40) NOT NULL DEFAULT '',
  x SMALLINT NOT NULL DEFAULT 0,
  y SMALLINT NOT NULL DEFAULT 0,
  zone_id INT UNSIGNED NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'available',
  mic TINYINT(1) NOT NULL DEFAULT 0,
  cam TINYINT(1) NOT NULL DEFAULT 0,
  screen TINYINT(1) NOT NULL DEFAULT 0,
  call_with INT UNSIGNED NULL,
  last_seen INT UNSIGNED NOT NULL DEFAULT 0,
  KEY k_seen (last_seen)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS ng_signals (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  to_peer VARCHAR(40) NOT NULL,
  from_peer VARCHAR(40) NOT NULL,
  from_user INT UNSIGNED NOT NULL,
  payload MEDIUMTEXT NOT NULL,
  created_at INT UNSIGNED NOT NULL,
  KEY k_to (to_peer),
  KEY k_created (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS ng_messages (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  sender_id INT UNSIGNED NOT NULL,
  scope VARCHAR(8) NOT NULL,
  target_id INT UNSIGNED NOT NULL DEFAULT 0,
  body TEXT NOT NULL,
  created_at INT UNSIGNED NOT NULL,
  KEY k_scope (scope, target_id, id),
  KEY k_sender (sender_id, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS ng_zones (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(64) NOT NULL,
  kind VARCHAR(16) NOT NULL DEFAULT 'talk',
  x SMALLINT NOT NULL,
  y SMALLINT NOT NULL,
  w SMALLINT NOT NULL,
  h SMALLINT NOT NULL,
  color VARCHAR(16) NOT NULL DEFAULT '#34d399'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS ng_settings (
  k VARCHAR(32) NOT NULL PRIMARY KEY,
  v TEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
